def assert_same_keys(a: object, b: object, path: str) -> None:
    if isinstance(a, dict) and isinstance(b, dict):
        if set(a) != set(b):
            raise SystemExit(f"key mismatch at {path}: {sorted(set(a) ^ set(b))}")
        for k in a:
            assert_same_keys(a[k], b[k], f"{path}.{k}")


def main() -> None:
    from i18n_data_public import PUBLIC_EN, PUBLIC_JA
    from i18n_data_rest import CHANNEL, USER

    extra = json.loads(Path(__file__).with_name("i18n-remain-extra.json").read_text())
    assert_same_keys(extra["zh"], PUBLIC_EN, "public")
    assert_same_keys(PUBLIC_EN, PUBLIC_JA, "public-en-ja")
    assert_same_keys(USER["zh"], USER["en"], "user")
    assert_same_keys(USER["en"], USER["ja"], "user-en-ja")
    assert_same_keys(CHANNEL["zh"], CHANNEL["en"], "channel")
    assert_same_keys(CHANNEL["en"], CHANNEL["ja"], "channel-en-ja")

    extras = {"zh": extra["zh"], "en": PUBLIC_EN, "ja": PUBLIC_JA}
    for locale in ("zh", "en", "ja"):
        path = ROOT / f"{locale}.json"
        data = json.loads(path.read_text())
        data = deep_merge(data, locale_patch(locale))
        data = deep_merge(data, extras[locale])
        data["user"] = USER[locale]
        data["channelUi"] = CHANNEL[locale]
        path.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n")
        print(f"wrote {path}")


if __name__ == "__main__":
    main()
