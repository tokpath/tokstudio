def deep_merge(dst: dict, src: dict) -> dict:
    for k, v in src.items():
        if isinstance(v, dict) and isinstance(dst.get(k), dict):
            deep_merge(dst[k], v)
        else:
            dst[k] = v
    return dst


def pick(ns: dict, locale: str) -> dict:
    out = {}
    for key, by_locale in ns.items():
        out[key] = by_locale[locale]
    return out


# Flatten PATCH which is {namespace: {zh|en|ja: keys}} into {namespace: keys} per locale
def locale_patch(locale: str) -> dict:
    out: dict = {}
    for ns, by_locale in PATCH.items():
        out[ns] = by_locale[locale]
    return out


