import { test, expect } from "@playwright/test";
import { readFileSync } from "node:fs";
const ready = process.env.TOKENHUB_STOCK_ACCEPTANCE_FILE;
test.skip(!ready, "Requires the isolated stock purchase application and PostgreSQL");
test("unconfigured channel can buy stock and sees preparation and blocked-quote explanations beside the action", async ({page}, info) => {
  const fixture = JSON.parse(readFileSync(ready!, "utf8"));
  await page.goto("/login");
  await page.getByLabel("邮箱",{exact:true}).fill(fixture.owner_email);
  await page.getByLabel("密码",{exact:true}).fill(fixture.owner_password);
  await page.getByRole("button",{name:"登录",exact:true}).click();
  await page.waitForURL(/\/manage\//);
  const path=`/manage/${fixture.operator_id}/procurement`;
  await page.goto(path+"?section=quotes");
  await expect(page.getByRole("status").filter({hasText:"可先采购备货"})).toBeVisible();
  await expect(page.getByRole("button",{name:"按金额采购",exact:true})).toBeEnabled();
  await page.screenshot({path:info.outputPath("stock-purchase-before-models.png"),fullPage:true});
  await page.getByRole("button",{name:"按金额采购",exact:true}).click();
  const panel=page.getByRole("dialog").last();
  await panel.getByLabel("本次采购USD",{exact:true}).fill("1000");
  await panel.getByRole("checkbox").check();
  const saved=page.waitForResponse(response=>response.url().endsWith("/purchase")&&response.request().method()==="POST");
  await panel.getByRole("button",{name:"按金额采购",exact:true}).click();
  const response=await saved;
  expect(response.status()).toBe(200);
  expect((await response.json()).status).toBe("awaiting_payment");
  await panel.getByRole("button",{name:"关闭办理面板",exact:true}).click();
  await page.getByRole("tab",{name:"采购订单",exact:true}).click();
  await expect(page.getByText("付款后自动发放采购额度；未付款订单可取消。",{exact:true})).toBeVisible();
  await page.goto(`/manage/${fixture.supplier_id}/procurement?view=supplier&section=quotes`);
  await page.getByRole("button",{name:"停止按此报价下单",exact:true}).click();
  const stop=page.getByRole("dialog").last();
  await stop.getByRole("checkbox").check();
  const stopped=page.waitForResponse(response=>response.url().endsWith("/disable_quote")&&response.request().method()==="POST");
  await stop.getByRole("button",{name:"停止按此报价下单",exact:true}).click();
  expect((await stopped).status()).toBe(200);
  await stop.getByRole("button",{name:"关闭办理面板",exact:true}).click();
  await page.goto(path+"?section=quotes");
  await expect(page.getByRole("button",{name:"按金额采购",exact:true})).toBeDisabled();
  await expect(page.getByText("该报价已停用，请联系供货方确认。",{exact:true})).toBeVisible();
  await expect(page.getByRole("status").filter({hasText:"可先采购备货"})).toHaveCount(0);
  await page.screenshot({path:info.outputPath("stock-purchase-disabled-explained.png"),fullPage:true});
});
