import { test, expect } from "@playwright/test";
import { readFileSync } from "node:fs";

const ready = process.env.TOKENHUB_FRONTEND_ACCEPTANCE_FILE;
test.skip(!ready, "Requires the real isolated application and PostgreSQL");

test("owner manages business switches, scoped restrictions, staff permissions and readable notifications", async ({ page }, testInfo) => {
  const fixture = JSON.parse(readFileSync(ready!, "utf8"));
  const op = fixture.personas.customers.other_operator_id;
  await page.goto("/login");
  await page.getByLabel("邮箱", { exact: true }).fill(fixture.owner_email);
  await page.getByLabel("密码", { exact: true }).fill(fixture.owner_password);
  await page.getByRole("button", { name: "登录", exact: true }).click();
  await page.waitForURL(/\/manage\//);
  const root = `/manage/${op}`;
  await page.goto(`${root}/business-status`);
  await expect(page.getByRole("button", { name: "暂停 资金结算", exact: true })).toBeEnabled();
  await expect(page.getByRole("textbox")).toHaveCount(0);
  await page.getByRole("button", { name: "暂停 资金结算", exact: true }).click();
  await expect(page.getByRole("button", { name: "开启 资金结算", exact: true })).toBeEnabled();
  await page.getByRole("button", { name: "开启 资金结算", exact: true }).click();
  await expect(page.getByRole("button", { name: "暂停 资金结算", exact: true })).toBeEnabled();
  await page.screenshot({ path: testInfo.outputPath("settings-business-switches.png"), fullPage: true });

  await page.goto(`${root}/restrictions`);
  await page.getByRole("button", { name: "新增业务限制", exact: true }).click();
  let panel = page.getByRole("dialog").last();
  const subject = panel.getByRole("combobox", { name: "限制对象", exact: true });
  await expect(subject).toBeEnabled(); await subject.fill(op);
  await panel.getByLabel("限制动作", { exact: true }).selectOption("activity");
  await panel.getByLabel("处理说明（向客户展示）", { exact: true }).fill("Browser scoped review");
  await panel.getByLabel("复核时间", { exact: true }).fill(new Date(Date.now() + 86400_000).toISOString().slice(0, 16));
  await expect(panel.getByLabel("内部复核依据", { exact: true })).toHaveCount(0);
  await panel.getByRole("checkbox").check();
  const create = page.waitForResponse(response => response.url().endsWith(`/operators/${op}/restrictions`) && response.request().method() === "POST");
  await panel.getByRole("button", { name: "新增业务限制", exact: true }).click();
  expect((await create).status()).toBe(200);
  await panel.getByRole("button", { name: "关闭办理面板", exact: true }).click();
  await page.getByRole("row").filter({ hasText: "Browser scoped review" }).getByRole("button", { name: "变更此项已有业务限制", exact: true }).click();
  panel = page.getByRole("dialog").last();
  await panel.getByRole("radiogroup", { name: "继续限制", exact: true }).getByRole("radio", { name: "否", exact: true }).check();
  await expect(panel.getByLabel("复核时间", { exact: true })).toHaveCount(0);
  const release = page.waitForResponse(response => response.url().endsWith(`/operators/${op}/restrictions`) && response.request().method() === "POST");
  await panel.getByRole("button", { name: "变更此项已有业务限制", exact: true }).click();
  expect((await release).status()).toBe(200);
  await panel.getByRole("button", { name: "关闭办理面板", exact: true }).click();

  await page.goto(`${root}/staff`);
  await page.getByRole("button", { name: "开通或邀请经营人员", exact: true }).click();
  panel = page.getByRole("dialog").last();
  await expect(panel.getByLabel("角色", { exact: true })).toBeVisible();
  await panel.getByRole("button", { name: "关闭办理面板", exact: true }).click();
  await page.goto(`${root}/notifications`);
  await page.getByRole("button", { name: "发送业务通知", exact: true }).click();
  panel = page.getByRole("dialog").last();
  const recipient = panel.locator('[data-command-field="recipient_id"]').getByRole("combobox");
  await expect(recipient).toBeEnabled(); await recipient.fill(fixture.owner_email);
  await page.getByRole("option").filter({ hasText: fixture.owner_email }).first().click();
  await panel.getByLabel("通知类别", { exact: true }).selectOption("mandatory");
  await panel.getByLabel("标题", { exact: true }).fill("Browser readable notice");
  await panel.getByLabel("通知正文", { exact: true }).fill("Simple settings verified");
  const announce = page.waitForResponse(response => response.url().endsWith(`/operators/${op}/notifications`) && response.request().method() === "POST");
  await panel.getByRole("button", { name: "发送业务通知", exact: true }).click();
  expect((await announce).status()).toBe(200);
  await panel.getByRole("button", { name: "关闭办理面板", exact: true }).click();
  await expect(page.getByRole("row").filter({ hasText: "Browser readable notice" })).toBeVisible();
  await page.screenshot({ path: testInfo.outputPath("settings-readable-notifications.png"), fullPage: true });
  await page.goto(`${root}/audit`);
  await expect(page.getByRole("heading", { name: "操作审计", exact: true })).toBeVisible();
  await expect(page.getByText("异步结果暂存", { exact: true })).toBeVisible();
});
